function getFilteredNEG(target) {
  const filtered = NEG_PATTERNS_DB.filter(p =>
    p.chars.includes('*') || p.chars.includes(target)
  );
  return filtered.map(p => `- ${p.id}: ${p.text}`).join('\n');
}

